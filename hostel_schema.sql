-- ---------- tables (parents first) ----------
CREATE TABLE ROOM (
    ROOM_NO   NUMBER(4) PRIMARY KEY,
    BLOCK     VARCHAR2(10) NOT NULL,
    CAPACITY  NUMBER(2) NOT NULL,
    OCCUPIED  NUMBER(2) DEFAULT 0,
    RENT      NUMBER(8,2) NOT NULL,
    CONSTRAINT CHK_OCC CHECK (OCCUPIED <= CAPACITY)
);

CREATE TABLE STUDENT (
    STUDENT_ID     NUMBER(6) PRIMARY KEY,
    REG_NO         VARCHAR2(15) NOT NULL UNIQUE,
    NAME           VARCHAR2(50) NOT NULL,
    PHONE          VARCHAR2(15),
    EMAIL          VARCHAR2(60),
    DEPARTMENT     VARCHAR2(30) NOT NULL,
    YEAR_OF_STUDY  NUMBER(1) NOT NULL CHECK (YEAR_OF_STUDY BETWEEN 1 AND 5),
    GUARDIAN_PHONE VARCHAR2(15),
    ROOM_NO        NUMBER(4) REFERENCES ROOM(ROOM_NO),
    JOIN_DATE      DATE DEFAULT SYSDATE
);

CREATE TABLE WARDEN (
    WARDEN_ID  NUMBER(4) PRIMARY KEY,
    NAME       VARCHAR2(50) NOT NULL,
    PHONE      VARCHAR2(15),
    EMAIL      VARCHAR2(60),
    BLOCK      VARCHAR2(10) NOT NULL,
    SHIFT_TIME VARCHAR2(10) CHECK (SHIFT_TIME IN ('Morning','Evening','Night'))
);

CREATE TABLE FEE (
    FEE_ID     NUMBER(8) PRIMARY KEY,
    STUDENT_ID NUMBER(6) NOT NULL REFERENCES STUDENT(STUDENT_ID) ON DELETE CASCADE,
    FEE_TYPE   VARCHAR2(20) NOT NULL CHECK (FEE_TYPE IN ('Room Rent','Mess','Maintenance','Fine','Other')),
    AMOUNT     NUMBER(8,2) NOT NULL CHECK (AMOUNT > 0),
    DUE_DATE   DATE NOT NULL,
    PAID_DATE  DATE,
    PAY_MODE   VARCHAR2(15) CHECK (PAY_MODE IN ('Cash','UPI','Card','Net Banking'))
);

CREATE TABLE COMPLAINT (
    COMPLAINT_ID NUMBER(8) PRIMARY KEY,
    STUDENT_ID   NUMBER(6) NOT NULL REFERENCES STUDENT(STUDENT_ID) ON DELETE CASCADE,
    CATEGORY     VARCHAR2(15) NOT NULL CHECK (CATEGORY IN ('Electrical','Plumbing','Furniture','Cleaning','Internet','Other')),
    DESCRIPTION  VARCHAR2(300) NOT NULL,
    PRIORITY     VARCHAR2(10) DEFAULT 'Medium' CHECK (PRIORITY IN ('Low','Medium','High')),
    STATUS       VARCHAR2(15) DEFAULT 'Open' CHECK (STATUS IN ('Open','In Progress','Resolved')),
    CREATED_ON   DATE DEFAULT SYSDATE,
    RESOLVED_ON  DATE
);

CREATE TABLE VISITOR (
    VISITOR_ID   NUMBER(8) PRIMARY KEY,
    STUDENT_ID   NUMBER(6) NOT NULL REFERENCES STUDENT(STUDENT_ID) ON DELETE CASCADE,
    VISITOR_NAME VARCHAR2(50) NOT NULL,
    RELATION     VARCHAR2(15) CHECK (RELATION IN ('Parent','Sibling','Relative','Friend','Other')),
    PHONE        VARCHAR2(15),
    IN_TIME      DATE DEFAULT SYSDATE NOT NULL,
    OUT_TIME     DATE
);

CREATE TABLE LEAVE_REQUEST (
    LEAVE_ID   NUMBER(8) PRIMARY KEY,
    STUDENT_ID NUMBER(6) NOT NULL REFERENCES STUDENT(STUDENT_ID) ON DELETE CASCADE,
    LEAVE_FROM DATE NOT NULL,
    LEAVE_TO   DATE NOT NULL,
    REASON     VARCHAR2(200) NOT NULL,
    STATUS     VARCHAR2(10) DEFAULT 'Pending' CHECK (STATUS IN ('Pending','Approved','Rejected')),
    APPLIED_ON DATE DEFAULT SYSDATE,
    CONSTRAINT CHK_LEAVE_DATES CHECK (LEAVE_TO >= LEAVE_FROM)
);

CREATE TABLE INVENTORY (
    ITEM_ID        NUMBER(8) PRIMARY KEY,
    ROOM_NO        NUMBER(4) NOT NULL REFERENCES ROOM(ROOM_NO) ON DELETE CASCADE,
    ITEM_NAME      VARCHAR2(40) NOT NULL,
    QUANTITY       NUMBER(3) DEFAULT 1 CHECK (QUANTITY >= 0),
    ITEM_CONDITION VARCHAR2(15) DEFAULT 'Good' CHECK (ITEM_CONDITION IN ('Good','Needs Repair','Damaged')),
    LAST_CHECKED   DATE
);

CREATE TABLE NOTICE (
    NOTICE_ID NUMBER(6) PRIMARY KEY,
    TITLE     VARCHAR2(80) NOT NULL,
    BODY      VARCHAR2(1000) NOT NULL,
    PRIORITY  VARCHAR2(10) DEFAULT 'Normal' CHECK (PRIORITY IN ('Normal','Important','Urgent')),
    POSTED_BY VARCHAR2(30),
    POSTED_ON DATE DEFAULT SYSDATE
);

CREATE TABLE APP_USER (
    USERNAME      VARCHAR2(30) PRIMARY KEY,
    PASSWORD_HASH VARCHAR2(100) NOT NULL,
    SALT          VARCHAR2(40) NOT NULL,
    ROLE          VARCHAR2(10) NOT NULL CHECK (ROLE IN ('ADMIN','VIEWER')),
    CREATED_ON    DATE DEFAULT SYSDATE,
    LAST_LOGIN    DATE
);

CREATE TABLE AUDIT_LOG (
    LOG_ID     NUMBER(10) PRIMARY KEY,
    USERNAME   VARCHAR2(30),
    ACTION     VARCHAR2(30),
    TABLE_NAME VARCHAR2(30),
    DETAIL     VARCHAR2(300),
    LOG_TIME   DATE DEFAULT SYSDATE
);

